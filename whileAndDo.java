

public class whileAndDo {
     public static void main(String[] args) {
         int a=12;
         while(a<11){
             System.out.println("hello"); //it won't give the answer becaouse the condition is false
         }
         do { 
             System.out.println("hello");//it willrun atleast one time if the condition become false
            
         } while (a<11);
     }
    
 }


 